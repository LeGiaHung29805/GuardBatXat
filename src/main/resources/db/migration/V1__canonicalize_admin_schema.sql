        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'batxat_users'::regclass
          AND conname = 'batxat_users_default_building_id_fkey'
    ) THEN
        ALTER TABLE batxat_users
            ADD CONSTRAINT batxat_users_default_building_id_fkey

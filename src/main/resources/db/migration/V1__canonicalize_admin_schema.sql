-- Normalize role names without relying on conflicting numeric role IDs.
DO $$
DECLARE
    viewer_role_id integer;
    citizen_role_id integer;
BEGIN
    SELECT role_id INTO viewer_role_id
    FROM batxat_roles
    WHERE role_name = 'VIEWER';

    SELECT role_id INTO citizen_role_id
    FROM batxat_roles
    WHERE role_name = 'CITIZEN';

    IF viewer_role_id IS NOT NULL AND citizen_role_id IS NULL THEN
        UPDATE batxat_roles
        SET role_name = 'CITIZEN', description = 'Người dân'
        WHERE role_id = viewer_role_id;
    ELSIF viewer_role_id IS NOT NULL THEN
        UPDATE batxat_users
        SET role_id = citizen_role_id
        WHERE role_id = viewer_role_id;

        DELETE FROM batxat_roles
        WHERE role_id = viewer_role_id;
    END IF;
END
$$;

INSERT INTO batxat_roles (role_name, description)
SELECT required.role_name, required.description
FROM (VALUES
    ('CITIZEN', 'Người dân'),
    ('RESCUE_TEAM', 'Đội cứu hộ'),
    ('COMMANDER', 'Trung tâm chỉ huy'),
    ('ADMIN', 'Quản trị viên hệ thống')
) AS required(role_name, description)
WHERE NOT EXISTS (
    SELECT 1
    FROM batxat_roles existing
    WHERE existing.role_name = required.role_name
);


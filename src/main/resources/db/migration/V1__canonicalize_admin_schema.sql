-- Validate AHP values while allowing the existing five-decimal rounding.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'batxat_ahp_weights'::regclass
          AND conname = 'batxat_ahp_weights_range_check'
    ) THEN
        ALTER TABLE batxat_ahp_weights
            ADD CONSTRAINT batxat_ahp_weights_range_check CHECK (
                w_distance BETWEEN 0 AND 1 AND
                w_flood BETWEEN 0 AND 1 AND
                w_landslide BETWEEN 0 AND 1 AND
                w_capacity BETWEEN 0 AND 1 AND
                w_bridge BETWEEN 0 AND 1 AND
                w_report BETWEEN 0 AND 1
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'batxat_ahp_weights'::regclass
          AND conname = 'batxat_ahp_weights_sum_check'
    ) THEN
        ALTER TABLE batxat_ahp_weights
            ADD CONSTRAINT batxat_ahp_weights_sum_check CHECK (
                abs((w_distance + w_flood + w_landslide + w_capacity + w_bridge + w_report)::double precision - 1.0) <= 0.001
            );
    END IF;
END
$$;

-- Recreate the routing function after normalizing the edge key/cost types.
DROP FUNCTION IF EXISTS get_daily_routing_costs(character varying);

CREATE FUNCTION get_daily_routing_costs(p_strategy character varying)
RETURNS TABLE(
    u bigint,
    v bigint,
    key integer,
    final_cost double precision,
    risk_level character varying
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_f_risk double precision;
    v_l_risk double precision;
    v_w record;
BEGIN
    SELECT
        COALESCE(flood_risk_pct / 100, 0.5)::double precision,
        COALESCE(landslide_risk_pct / 100, 0.5)::double precision
    INTO v_f_risk, v_l_risk
    FROM batxat_daily_risk
    WHERE forecast_date = CURRENT_DATE;

    IF v_f_risk IS NULL THEN
        v_f_risk := 0.5;
        v_l_risk := 0.5;
    END IF;

    SELECT * INTO v_w
    FROM batxat_ahp_weights
    WHERE strategy_name = p_strategy;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown routing strategy: %', p_strategy;
    END IF;

    RETURN QUERY
    SELECT
        e.u,
        e.v,
        e.key,
        (
            COALESCE(v_w.w_distance, 0)::double precision * e.length_m +
            COALESCE(v_w.w_flood, 0)::double precision * (v_f_risk * (1000 / (e.avg_elevation + 1)) * 10000) +
            COALESCE(v_w.w_landslide, 0)::double precision * (v_l_risk * (e.avg_slope / 35.0) * 15000) +
            COALESCE(v_w.w_capacity, 0)::double precision * (e.road_capacity * 1000) +
            COALESCE(v_w.w_bridge, 0)::double precision * (e.is_bridge * 5000) +
            COALESCE(v_w.w_report, 0)::double precision * (e.community_report * 20000)
        )::double precision AS final_cost,
        CASE
            WHEN (v_l_risk * (e.avg_slope / 35.0)) > 0.7 THEN 'CỰC KỲ NGUY HIỂM'
            WHEN (v_f_risk * (1000 / (e.avg_elevation + 1))) > 0.5 THEN 'NGUY CƠ NGẬP'
            ELSE 'ỔN ĐỊNH'
        END::character varying AS risk_level
    FROM batxat_road_edges e;
END;
$$;

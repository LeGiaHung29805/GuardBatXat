    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'batxat_users'::regclass
          AND conname = 'batxat_users_trust_score_check'
    ) THEN
        ALTER TABLE batxat_users
            ADD CONSTRAINT batxat_users_trust_score_check
            CHECK (trust_score IS NULL OR trust_score BETWEEN 0 AND 1);
    END IF;
END
$$;

